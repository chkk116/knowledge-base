/** 最新一条「Web 正式版」说明：跳过 `-native` 后缀的原生壳专属条目，避免 Web 端把原生功能当成本版更新 */
export const CURRENT_VERSION = CHANGELOG.find((c) => !/-native$/.test(c.version)) || CHANGELOG[0]

/** 按 versionName 取该版本的更新说明（取不到返回 null） */
export function changelogOf(versionName) {
  const v = String(versionName || '').replace(/^v/, '').trim()
  if (!v) return null
  // 容忍预发布后缀：1.2.0-beta2 → 匹配 1.2.0
  const base = v.replace(/[-+].*$/, '')
  return CHANGELOG.find((c) => c.version === v)
    || CHANGELOG.find((c) => c.version === base)
    || null
}

/**
 * 把后台下发的 notes 解析成条目数组。
 * 兼容：换行分隔、"1. xxx；2. yyy"、"- xxx"、"· xxx" 等常见写法。
 */
export function parseNotes(notes) {
  const s = String(notes || '').trim()
  if (!s) return []
  return s
    .split(/\r?\n|；|;/)
    .map((x) => x.trim())
    .filter(Boolean)
    .map((x) => x.replace(/^[-·•*]\s*/, '').replace(/^\d+\s*[.、)]\s*/, '').trim())
    .filter(Boolean)
}
